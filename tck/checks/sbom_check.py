"""SBOM comparison check for the s-core TCK.

Compares the distribution's SPDX SBOM against the golden reference SBOM:
- Required components present (from known_good.json sbom.tracked_modules)
- No forbidden components (catches unexpected third-party deps)
- License policy compliance (all licenses in allowed set)
- Informational drift report (version/hash differences from golden)

The golden SBOM is generated by //:sbom in the reference integration build.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Set


@dataclass
class CheckResult:
    """Result of a single check within the SBOM comparison."""

    check_id: str
    status: str  # pass | fail | warn | skip
    severity: str  # required | recommended | informational
    message: str
    details: List[Dict[str, Any]] = field(default_factory=list)


@dataclass
class SBOMCheckReport:
    """Full SBOM check report."""

    dist_name: str
    dist_sbom_path: str
    golden_sbom_path: str
    checks: List[CheckResult] = field(default_factory=list)

    @property
    def verdict(self) -> str:
        """Overall verdict: CONFORMANT | NON-CONFORMANT | CONFORMANT-WITH-WARNINGS."""
        has_fail = any(c.status == "fail" and c.severity == "required" for c in self.checks)
        has_warn = any(c.status == "warn" for c in self.checks)
        if has_fail:
            return "NON-CONFORMANT"
        if has_warn:
            return "CONFORMANT-WITH-WARNINGS"
        return "CONFORMANT"

    def to_json(self) -> Dict[str, Any]:
        return {
            "check_family": "sbom",
            "dist_name": self.dist_name,
            "dist_sbom_path": self.dist_sbom_path,
            "golden_sbom_path": self.golden_sbom_path,
            "checks": [
                {
                    "check_id": c.check_id,
                    "status": c.status,
                    "severity": c.severity,
                    "message": c.message,
                    "details": c.details,
                }
                for c in self.checks
            ],
            "verdict": self.verdict,
        }


def load_spdx(path: Path) -> Dict[str, Any]:
    """Load an SPDX JSON file."""
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def extract_packages(spdx: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    """Extract packages as a dict keyed by package name (lowercase for matching)."""
    packages = {}
    for pkg in spdx.get("packages", []):
        name = pkg.get("name", "").lower()
        packages[name] = {
            "name": pkg.get("name"),
            "version": pkg.get("versionInfo", "unknown"),
            "license": pkg.get("licenseConcluded", "NOASSERTION"),
            "supplier": pkg.get("supplier", ""),
            "downloadLocation": pkg.get("downloadLocation", ""),
            "checksums": {c["algorithm"]: c["checksumValue"] for c in pkg.get("checksums", [])},
        }
    return packages


class SBOMChecker:
    """SBOM comparison checker."""

    # Default allowed licenses (can be overridden by policy file)
    DEFAULT_ALLOWED_LICENSES = {
        "Apache-2.0",
        "MIT",
        "BSD-2-Clause",
        "BSD-3-Clause",
        "CC0-1.0",
        "ISC",
        "Zlib",
        "NOASSERTION",  # Allow if we couldn't determine; flagged in drift
    }

    def __init__(
        self,
        golden_sbom_path: Path,
        required_modules: Optional[Set[str]] = None,
        allowed_licenses: Optional[Set[str]] = None,
        forbidden_components: Optional[Set[str]] = None,
    ):
        self.golden_sbom_path = golden_sbom_path
        self.golden_spdx = load_spdx(golden_sbom_path)
        self.golden_packages = extract_packages(self.golden_spdx)

        self.required_modules = required_modules or set()
        self.allowed_licenses = allowed_licenses or self.DEFAULT_ALLOWED_LICENSES
        self.forbidden_components = forbidden_components or set()

    def check(self, dist_sbom_path: Path) -> SBOMCheckReport:
        """Run all SBOM checks against the distribution's SBOM."""
        dist_spdx = load_spdx(dist_sbom_path)
        dist_packages = extract_packages(dist_spdx)

        dist_name = dist_spdx.get("name", "unknown-distribution")

        report = SBOMCheckReport(
            dist_name=dist_name,
            dist_sbom_path=str(dist_sbom_path),
            golden_sbom_path=str(self.golden_sbom_path),
        )

        # Check 1: Required components present
        report.checks.append(self._check_required_components(dist_packages))

        # Check 2: No forbidden components
        report.checks.append(self._check_forbidden_components(dist_packages))

        # Check 3: License policy
        report.checks.append(self._check_license_policy(dist_packages))

        # Check 4: Drift from golden (informational)
        report.checks.append(self._check_drift(dist_packages))

        return report

    def _check_required_components(self, dist_packages: Dict[str, Dict]) -> CheckResult:
        """Verify all required modules from known_good.json are present."""
        missing = []
        for module in self.required_modules:
            if module.lower() not in dist_packages:
                missing.append(module)

        if missing:
            return CheckResult(
                check_id="sbom.required_components",
                status="fail",
                severity="required",
                message=f"Missing {len(missing)} required component(s)",
                details=[{"module": m} for m in sorted(missing)],
            )
        return CheckResult(
            check_id="sbom.required_components",
            status="pass",
            severity="required",
            message=f"All {len(self.required_modules)} required components present",
            details=[{"module": m, "found": True} for m in sorted(self.required_modules)],
        )

    def _check_forbidden_components(self, dist_packages: Dict[str, Dict]) -> CheckResult:
        """Check for forbidden/undesired components."""
        found_forbidden = []
        for forbidden in self.forbidden_components:
            if forbidden.lower() in dist_packages:
                found_forbidden.append(forbidden)

        if found_forbidden:
            return CheckResult(
                check_id="sbom.forbidden_components",
                status="fail",
                severity="required",
                message=f"Found {len(found_forbidden)} forbidden component(s)",
                details=[{"component": c} for c in sorted(found_forbidden)],
            )
        return CheckResult(
            check_id="sbom.forbidden_components",
            status="pass",
            severity="required",
            message="No forbidden components found",
            details=[],
        )

    def _check_license_policy(self, dist_packages: Dict[str, Dict]) -> CheckResult:
        """Verify all component licenses are allowed."""
        violations = []
        for name, pkg in dist_packages.items():
            license_val = pkg.get("license", "NOASSERTION")
            # SPDX license expressions can be complex (e.g., "Apache-2.0 OR MIT")
            # For v1, we check if any disallowed license appears
            if license_val not in self.allowed_licenses:
                # Check if it's a compound expression with allowed licenses
                if not any(allowed in license_val for allowed in self.allowed_licenses if allowed != "NOASSERTION"):
                    violations.append(
                        {"component": name, "license": license_val, "allowed": sorted(self.allowed_licenses)}
                    )

        if violations:
            return CheckResult(
                check_id="sbom.license_policy",
                status="fail" if any(v["license"] not in self.DEFAULT_ALLOWED_LICENSES for v in violations) else "warn",
                severity="required",
                message=f"Found {len(violations)} license policy violation(s)",
                details=violations[:20],  # Cap details for readability
            )
        return CheckResult(
            check_id="sbom.license_policy",
            status="pass",
            severity="required",
            message="All licenses comply with policy",
            details=[],
        )

    def _check_drift(self, dist_packages: Dict[str, Dict]) -> CheckResult:
        """Report version/hash drift from golden (informational)."""
        drift = []

        # Components in golden but different in dist
        for name, golden_pkg in self.golden_packages.items():
            if name in dist_packages:
                dist_pkg = dist_packages[name]
                if golden_pkg.get("version") != dist_pkg.get("version"):
                    drift.append(
                        {
                            "component": name,
                            "type": "version",
                            "golden": golden_pkg.get("version"),
                            "dist": dist_pkg.get("version"),
                        }
                    )

        # Components in dist but not in golden (additions)
        for name in dist_packages:
            if name not in self.golden_packages:
                drift.append(
                    {
                        "component": name,
                        "type": "addition",
                        "golden": "absent",
                        "dist": "present",
                    }
                )

        if drift:
            return CheckResult(
                check_id="sbom.drift",
                status="warn",
                severity="informational",
                message=f"Found {len(drift)} drift item(s) from golden reference",
                details=drift[:50],  # Cap for readability
            )
        return CheckResult(
            check_id="sbom.drift",
            status="pass",
            severity="informational",
            message="No drift from golden reference",
            details=[],
        )
